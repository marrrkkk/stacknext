import { describe, expect, it } from 'vitest'
import {
  extractReleaseNotes,
  parseChangelogReleases,
  renderChangelogModule,
} from './changelog.mjs'

describe('release notes extraction', () => {
  it('extracts one version section and stops at the next heading', () => {
    const changelog = [
      '# Changelog',
      '',
      '## [Unreleased]',
      '',
      '## [1.2.3] - 2026-01-02',
      '',
      '### Added',
      '',
      '- A feature.',
      '',
      '## [1.2.2] - 2026-01-01',
      '',
      '- An older fix.',
    ].join('\n')

    expect(extractReleaseNotes(changelog, '1.2.3')).toBe(
      '### Added\n\n- A feature.',
    )
  })

  it('ignores headings inside fenced code blocks', () => {
    const changelog = [
      '## [1.2.3] - 2026-01-02',
      '',
      '### Added',
      '',
      '```md',
      '## Example',
      '~~~',
      'not a fence because it has the wrong character',
      '```',
      '',
      'After the example.',
      '',
      '## [1.2.2] - 2026-01-01',
      '',
      '- An older fix.',
    ].join('\n')

    const notes = extractReleaseNotes(changelog, '1.2.3')
    expect(notes).toContain('## Example')
    expect(notes).toContain('After the example.')
    expect(notes).not.toContain('An older fix.')
  })

  it('does not match a longer version with the same prefix', () => {
    const changelog = [
      '## [1.2.30] - 2026-01-03',
      '',
      '- A newer patch.',
      '',
      '## [1.2.3] - 2026-01-02',
      '',
      '- The requested patch.',
    ].join('\n')

    expect(extractReleaseNotes(changelog, '1.2.3')).toBe('- The requested patch.')
  })

  it('falls back when the section is missing or empty', () => {
    expect(extractReleaseNotes('# Changelog\n', '9.9.9')).toBe('Release 9.9.9.')
    expect(extractReleaseNotes('## [1.0.0]\n\n## [0.9.0]\n', '1.0.0')).toBe('Release 1.0.0.')
  })
})

describe('website changelog parsing', () => {
  const changelog = [
    '# Changelog',
    '',
    '## [Unreleased]',
    '',
    '### Added',
    '',
    '- Not published yet.',
    '',
    '## [1.2.0] - 2026-01-02',
    '',
    'A **big** release with [`docs`](https://example.com/docs).',
    '',
    '### Added',
    '',
    '- Added `stacknext` with a',
    '  wrapped line.',
    '- Second item.',
    '',
    '### Breaking changes',
    '',
    '- Removed `old`.',
  ].join('\n')

  it('parses released sections and skips Unreleased', () => {
    const releases = parseChangelogReleases(changelog)
    expect(releases).toHaveLength(1)
    expect(releases[0]).toMatchObject({
      id: 'v1-2-0',
      version: '1.2.0',
      date: '2026-01-02',
      dateLabel: 'January 2, 2026',
    })
    expect(releases[0].intro[0]).toEqual([
      { type: 'text', value: 'A ' },
      { type: 'strong', children: [{ type: 'text', value: 'big' }] },
      { type: 'text', value: ' release with ' },
      {
        type: 'link',
        href: 'https://example.com/docs',
        children: [{ type: 'code', value: 'docs' }],
      },
      { type: 'text', value: '.' },
    ])
    expect(releases[0].groups.map((group) => group.title)).toEqual([
      'Added',
      'Breaking changes',
    ])
    expect(releases[0].groups[0].items[0]).toEqual([
      { type: 'text', value: 'Added ' },
      { type: 'code', value: 'stacknext' },
      { type: 'text', value: ' with a wrapped line.' },
    ])
    expect(releases[0].groups[0].items).toHaveLength(2)
  })

  it('renders a deterministic TypeScript module', () => {
    const releases = parseChangelogReleases(changelog)
    const module = renderChangelogModule(releases)
    expect(module).toContain('Generated by scripts/sync-changelog.mjs')
    expect(module).toContain(
      'export const CHANGELOG_RELEASES = [',
    )
    expect(module).toContain(
      'as const satisfies readonly ChangelogRelease[]',
    )
    expect(renderChangelogModule(releases)).toBe(module)
  })

  it('ignores HTML comments inside a release', () => {
    const source = [
      '## [1.0.0] - 2026-01-01',
      '',
      '### Added',
      '',
      '- A feature.',
      '',
      '<!-- coderabbit-ai-generated:v1 -->',
      '',
      '<!-- coderabbit-ai-generated-section:v1:abc123 -->',
      '',
      '### Fixed',
      '',
      '- A fix.',
      '',
      '<!-- /coderabbit-ai-generated:v1 -->',
    ].join('\n')

    const [release] = parseChangelogReleases(source)
    expect(release.intro).toEqual([])
    expect(release.groups.map((group) => group.title)).toEqual([
      'Added',
      'Fixed',
    ])
    expect(release.groups.map((group) => group.items.length)).toEqual([1, 1])
    expect(JSON.stringify(release)).not.toContain('coderabbit')
  })

  it('ignores headings inside fenced blocks outside a release', () => {
    const source = [
      '# Changelog',
      '',
      '```md',
      '## [9.9.9] - 2026-01-01',
      '```',
      '',
      '## [1.0.0] - 2026-01-01',
      '',
      '### Added',
      '',
      '- A release.',
    ].join('\n')
    expect(parseChangelogReleases(source).map((release) => release.version)).toEqual([
      '1.0.0',
    ])
  })

  it('rejects structure the website cannot render faithfully', () => {
    expect(() =>
      parseChangelogReleases('## [1.0.0] - 2026-01-01\n\n- A release.\n'),
    ).toThrow('has a bullet before the first "###" group')
    expect(() =>
      parseChangelogReleases('## [1.0.0]\n\n### Added\n\n- A release.\n'),
    ).toThrow('needs a date')
    expect(() =>
      parseChangelogReleases(
        '## [1.0.0] - 2026-01-01\n\n### Added\n\n- [docs](docs/privacy.md)\n',
      ),
    ).toThrow('must use an absolute http(s) URL')
    expect(() =>
      parseChangelogReleases(
        '## [1.0.0] - 2026-01-01\n\n### Added\n\n- [docs](https://example.com "Docs")\n',
      ),
    ).toThrow('unsupported Markdown link')
    expect(() =>
      parseChangelogReleases(
        '## [1.0.0] - 2026-01-01\n\n### Added\n\n- A release.\n  - Nested.\n',
      ),
    ).toThrow('nested list item')
    expect(() =>
      parseChangelogReleases(
        '## [1.0.0] - 2026-01-01\n\n### Added\n\n```ts\nconst value = 1\n```\n',
      ),
    ).toThrow('fenced code block')
    expect(() =>
      parseChangelogReleases('## [1.0.0] - 2026-01-01\n\n### Added\n'),
    ).toThrow('empty "Added" group')
  })
})
