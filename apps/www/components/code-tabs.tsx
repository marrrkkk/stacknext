const TOKEN_RE =
  /(\/\/[^\n]*)|(`[^`]*`|'[^']*'|"[^"]*")|\b(import|from|export|async|await|function|const|let|if|return|new|as|typeof|void|true|false|unknown|Promise|Parameters)\b/g

function highlight(line: string): ReactNode {
  const nodes: ReactNode[] = []
  let last = 0
  let match: RegExpExecArray | null
  TOKEN_RE.lastIndex = 0

  while ((match = TOKEN_RE.exec(line)) !== null) {
    if (match.index > last) nodes.push(line.slice(last, match.index))
    const className = match[1]
      ? 'text-[#5c5c5c] italic'
      : match[2]
        ? 'text-[#a9a9a9]'
        : 'text-[#f0f0f0]'
    nodes.push(
      <span className={className} key={`${match.index}-${match[0]}`}>
        {match[0]}
      </span>,
    )
    last = match.index + match[0].length
  }

  if (last < line.length) nodes.push(line.slice(last))
  return nodes.length > 0 ? nodes : '\u00a0'
}

export function CodeTabs(): React.ReactElement {
  const [activeId, setActiveId] = useState<Snippet['id']>('instrumentation')
  const tabRefs = useRef<Array<HTMLButtonElement | null>>([])

  const focusTab = (index: number): void => {
    const bounded = (index + SNIPPETS.length) % SNIPPETS.length
    const next = SNIPPETS[bounded]!
    setActiveId(next.id)
    tabRefs.current[bounded]?.focus()
  }

  return (
    <div className="min-w-0 overflow-hidden rounded-2xl border border-line-2 bg-[#080808]">
      <div
        className="flex gap-[3px] overflow-x-auto border-b border-line bg-[#0b0b0b] p-2 [scrollbar-width:none] [&::-webkit-scrollbar]:hidden max-560:p-[6px]"
        role="tablist"
        aria-label="Integration snippets"
      >
        {SNIPPETS.map((snippet, index) => (
          <button
            key={snippet.id}
            ref={(element) => {
              tabRefs.current[index] = element
            }}
            type="button"
            role="tab"
            id={`code-tab-${snippet.id}`}
            aria-selected={activeId === snippet.id}
            aria-controls={`code-panel-${snippet.id}`}
            tabIndex={activeId === snippet.id ? 0 : -1}
            className="h-8 rounded-[7px] px-3 text-[12.5px] font-medium whitespace-nowrap text-ink-2 transition-[background,color] duration-[160ms] ease-soft hover:bg-white/5 hover:text-ink aria-selected:bg-[#1a1a1a] aria-selected:text-ink max-560:h-[30px] max-560:px-[10px] max-560:text-[12px]"
            onClick={() => setActiveId(snippet.id)}
            onKeyDown={(event) => {
              if (event.key === 'ArrowRight') {
                event.preventDefault()
                focusTab(index + 1)
              } else if (event.key === 'ArrowLeft') {
                event.preventDefault()
                focusTab(index - 1)
              } else if (event.key === 'Home') {
                event.preventDefault()
                focusTab(0)
              } else if (event.key === 'End') {
                event.preventDefault()
                focusTab(SNIPPETS.length - 1)
              }
            }}
          >
            {snippet.label}
          </button>
        ))}
      </div>

      {SNIPPETS.map((snippet) => (
        <div
          key={snippet.id}
          role="tabpanel"
          id={`code-panel-${snippet.id}`}
          aria-labelledby={`code-tab-${snippet.id}`}
          hidden={activeId !== snippet.id}
          className="[&[hidden]]:hidden"
        >
          <div className="flex h-[38px] items-center justify-between gap-4 border-b border-line px-[14px] font-mono text-[11px] tracking-[0.04em] text-ink-3">
            <span>{snippet.filename}</span>
            <a
              className="inline-flex items-center gap-1 text-ink-2 transition-colors duration-[160ms] ease-soft hover:text-ink"
              href={snippet.href}
              target="_blank"
              rel="noreferrer"
            >
              Docs
              <ArrowUpRight width={11} height={11} aria-hidden />
            </a>
          </div>
          <pre
            className="m-0 max-h-[438px] overflow-auto py-[18px] text-[13px] leading-[1.75] [tab-size:2] [scrollbar-color:#333_#0b0b0b] max-560:max-h-[360px] max-560:text-[12px]"
            tabIndex={0}
          >
            <code>
              {snippet.lines.map((line, index) => (
                <span className="flex min-w-max pr-[18px]" key={`${snippet.id}-${index}`}>
                  <span
                    className="w-10 flex-none pr-4 text-right text-[#3f3f3f] select-none max-560:w-8 max-560:pr-3"
                    aria-hidden="true"
                  >
                    {String(index + 1).padStart(2, '0')}
                  </span>
                  <span className="whitespace-pre text-[#c9c9c9]">{highlight(line)}</span>
                </span>
              ))}
            </code>
          </pre>
          <p className="border-t border-line px-4 py-[14px] text-[12.5px] leading-[1.55] text-ink-3">
            {snippet.note}
          </p>
        </div>
      ))}
    </div>
  )
}
