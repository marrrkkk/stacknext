function manualPatchSnippet(): string {
  return [
    "import { registerNextScope, onRequestError as nextScopeOnRequestError } from '@nextscope/next'",
    '',
    '// Inside your existing register():',
    'await registerNextScope()',
    '',
    '// At module level, if you do not already export an error hook:',
    'export const onRequestError = nextScopeOnRequestError',
  ].join('\n')
}

async function exists(file: string): Promise<boolean> {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

async function runInstall(project: ProjectInfo): Promise<boolean> {
  const command = installCommand(project.packageManager, ['@nextscope/next'], true)
  const [bin, ...args] = command.split(' ')
  if (!bin) return false
  return new Promise((resolve) => {
    const child = spawn(bin, args, {
      cwd: project.dir,
      stdio: 'inherit',
      shell: process.platform === 'win32',
    })
    child.once('error', (error) => {
      printCheck('fail', 'Could not install @nextscope/next', error.message)
      resolve(false)
    })
    child.once('exit', (code) => resolve(code === 0))
  })
}

export interface InitOptions {
  install?: boolean
}

export async function runInit(options: InitOptions, cwd = process.cwd()): Promise<number> {
  const project = await detectProject(cwd)
  printSection(`NextScope init — ${project.name}`)

  if (project.nextVersion === null) {
    printCheck('fail', 'Next.js dependency not found', 'Install Next.js 15 or 16 first.')
    return 1
  }
  if (project.nextMajor !== null && project.nextMajor < 15) {
    printCheck(
      'fail',
      `Next.js ${project.nextVersion} is not supported`,
      'NextScope requires Next.js 15 or 16 with the App Router.',
    )
    return 1
  }
  if (project.nextMajor !== null && project.nextMajor > 16) {
    printCheck(
      'warn',
      `Next.js ${project.nextVersion} is newer than the tested range`,
      'NextScope supports Next.js 15 and 16.',
    )
  } else {
    printCheck('pass', `Next.js ${project.nextVersion}`)
  }

  if (!project.appDir) {
    printCheck(
      'fail',
      'App Router directory not found',
      'NextScope supports the App Router only (app/ or src/app/).',
    )
    return 1
  }
  printCheck('pass', `App Router at ${project.appDir}/`)

  const configFile = configPath(project.dir)
  if (!(await exists(configFile))) {
    const config = {
      projectName: project.name,
      dashboard: { port: 4400 },
      collector: { maxSpans: 5_000, retentionMs: 600_000 },
      instrumentation: { verbose: false, captureFetch: true, captureErrors: true },
      privacy: {
        captureHeaders: false,
        captureRequestBodies: false,
        captureSqlParameters: false,
        redactSensitiveData: true,
      },
      database: { drizzle: project.hasDrizzle, prisma: project.hasPrisma },
      slowRequestMs: 500,
    }
    await writeFile(configFile, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 })
    printCheck('pass', `Created ${CONFIG_FILE_NAME}`)
  } else {
    await loadConfig(project.dir)
    printCheck('pass', `${CONFIG_FILE_NAME} is valid`)
  }

  if (project.instrumentationExists && project.instrumentationPath) {
    const source = await readFile(project.instrumentationPath, 'utf8')
    if (isNextScopeIntegrated(source)) {
      printCheck('pass', 'Instrumentation already imports @nextscope/next')
    } else {
      printCheck(
        'warn',
        'Existing instrumentation.ts was left untouched',
        'Add the hook below so your current monitoring keeps working:',
      )
      console.log(`\n${manualPatchSnippet()}\n`)
    }
  } else {
    const target = instrumentationTarget(project)
    await writeFile(target, generatedInstrumentation(project.typescript), { mode: 0o600 })
    printCheck('pass', `Created ${path.relative(project.dir, target)}`)
  }

  const declared =
    project.dependencies['@nextscope/next'] ??
    project.devDependencies['@nextscope/next']
  if (!declared) {
    if (options.install) {
      const installed = await runInstall(project)
      if (installed) printCheck('pass', 'Installed @nextscope/next')
      else
        printCheck(
          'warn',
          'Install @nextscope/next before starting Next.js',
          installCommand(project.packageManager, ['@nextscope/next'], true),
        )
    } else {
      printCheck(
        'warn',
        '@nextscope/next is not installed',
        installCommand(project.packageManager, ['@nextscope/next'], true),
      )
    }
  } else {
    printCheck('pass', `@nextscope/next ${declared}`)
  }

  if (project.hasDrizzle) {
    printCheck(
      'warn',
      'Drizzle detected',
      'Add createNextScopeDrizzleLogger() from @nextscope/drizzle to your db client.',
    )
  }
  if (project.hasPrisma) {
    printCheck(
      'warn',
      'Prisma detected',
      'Add instrumentPrismaClient() from @nextscope/prisma after creating PrismaClient.',
    )
  }

  printSection('Next steps')
  console.log(
    `1. Run ${style.cyan('nextscope dev')} (or ${style.cyan('nextscope dev --install')} if packages are missing).`,
  )
  console.log(`2. Open the dashboard and make a request to your app.`)
  console.log(`3. Run ${style.cyan('nextscope doctor')} if data does not appear.`)
  return 0
}

export function registerInitCommand(program: Command, cwd: string): void {
  program
    .command('init')
    .description('Configure a Next.js project for NextScope')
    .option('--install', 'install @nextscope/next with the detected package manager')
    .action(async (options: InitOptions) => {
      const code = await runInit(options, cwd)
      if (code !== 0) process.exitCode = code
    })
}
