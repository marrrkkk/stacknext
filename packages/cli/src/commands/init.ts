import { spawn } from 'node:child_process'
import { access, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { Command } from 'commander'
import { CONFIG_FILE_NAME, configPath, loadConfig } from '@stacknext/core/config-file'
import {
  detectProject,
  installCommand,
  isStackNextIntegrated,
  type ProjectInfo,
} from '../project.js'
import { printCheck, printSection, style } from '../output.js'

function instrumentationTarget(project: ProjectInfo): string {
  const inSrc =
    project.appDir?.startsWith('src/') === true ||
    (project.appDir === null && project.srcDir)
  return path.join(
    project.dir,
    inSrc ? 'src' : '',
    `instrumentation.${project.typescript ? 'ts' : 'js'}`,
  )
}

export function generatedInstrumentation(typescript: boolean): string {
  if (typescript) {
    return `type StackNextRequest = {
  path: string
  method: string
  headers: NodeJS.Dict<string | string[]>
}

type StackNextRequestContext = {
  routerKind: 'Pages Router' | 'App Router'
  routePath: string
  routeType: 'render' | 'route' | 'action' | 'proxy'
  renderSource?: string
  revalidateReason: 'on-demand' | 'stale' | undefined
}

// Generated by StackNext. Node.js runtime only; no-op without a local collector.
export async function register(): Promise<void> {
  if (process.env.NEXT_RUNTIME !== 'nodejs') return
  const stacknext = await import('@stacknext/next')
  await stacknext.register()
}

export async function onRequestError(
  error: unknown,
  request: StackNextRequest,
  context: StackNextRequestContext,
): Promise<void> {
  if (process.env.NEXT_RUNTIME !== 'nodejs') return
  const stacknext = await import('@stacknext/next')
  stacknext.onRequestError(error, request, context)
}
`
  }
  return `// Generated by StackNext. Node.js runtime only; no-op without a local collector.
export async function register() {
  if (process.env.NEXT_RUNTIME !== 'nodejs') return
  const stacknext = await import('@stacknext/next')
  await stacknext.register()
}

export async function onRequestError(error, request, context) {
  if (process.env.NEXT_RUNTIME !== 'nodejs') return
  const stacknext = await import('@stacknext/next')
  stacknext.onRequestError(error, request, context)
}
`
}

export function isGeneratedInstrumentation(source: string): boolean {
  const normalized = source.replace(/\r\n/g, '\n').trimEnd()
  return (
    normalized === generatedInstrumentation(true).trimEnd() ||
    normalized === generatedInstrumentation(false).trimEnd()
  )
}

export function manualPatchSnippet(): string {
  return [
    "import { registerStackNext, onRequestError as stackNextOnRequestError } from '@stacknext/next'",
    '',
    '// Inside your existing register():',
    'await registerStackNext()',
    '',
    '// At module level, if you do not already export an error hook:',
    'export const onRequestError = stackNextOnRequestError',
  ].join('\n')
}

export async function fileExists(file: string): Promise<boolean> {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

async function runInstall(project: ProjectInfo): Promise<boolean> {
  const command = installCommand(project.packageManager, ['@stacknext/next'], true)
  const [bin, ...args] = command.split(' ')
  if (!bin) return false
  return new Promise((resolve) => {
    const child = spawn(bin, args, {
      cwd: project.dir,
      stdio: 'inherit',
      shell: process.platform === 'win32',
    })
    child.once('error', (error) => {
      printCheck('fail', 'Could not install @stacknext/next', error.message)
      resolve(false)
    })
    child.once('exit', (code) => resolve(code === 0))
  })
}

export interface InitOptions {
  install?: boolean
}

export async function runInit(options: InitOptions, cwd = process.cwd()): Promise<number> {
  const project = await detectProject(cwd)
  printSection(`StackNext init — ${project.name}`)

  if (project.nextVersion === null) {
    printCheck('fail', 'Next.js dependency not found', 'Install Next.js 15 or 16 first.')
    return 1
  }
  if (project.nextMajor !== null && project.nextMajor < 15) {
    printCheck(
      'fail',
      `Next.js ${project.nextVersion} is not supported`,
      'StackNext requires Next.js 15 or 16 with the App Router.',
    )
    return 1
  }
  if (project.nextMajor !== null && project.nextMajor > 16) {
    printCheck(
      'warn',
      `Next.js ${project.nextVersion} is newer than the tested range`,
      'StackNext supports Next.js 15 and 16.',
    )
  } else {
    printCheck('pass', `Next.js ${project.nextVersion}`)
  }

  if (!project.appDir) {
    printCheck(
      'fail',
      'App Router directory not found',
      'StackNext supports the App Router only (app/ or src/app/).',
    )
    return 1
  }
  printCheck('pass', `App Router at ${project.appDir}/`)

  const configFile = configPath(project.dir)
  if (!(await fileExists(configFile))) {
    const config = {
      projectName: project.name,
      dashboard: { port: 4400 },
      collector: { maxSpans: 5_000, retentionMs: 600_000 },
      instrumentation: { verbose: false, captureFetch: true, captureErrors: true },
      privacy: {
        captureHeaders: false,
        captureRequestBodies: false,
        captureSqlParameters: false,
        redactSensitiveData: true,
      },
      database: { drizzle: project.hasDrizzle, prisma: project.hasPrisma },
      slowRequestMs: 500,
    }
    await writeFile(configFile, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 })
    printCheck('pass', `Created ${CONFIG_FILE_NAME}`)
  } else {
    await loadConfig(project.dir)
    printCheck('pass', `${CONFIG_FILE_NAME} is valid`)
  }

  if (project.instrumentationExists && project.instrumentationPath) {
    const source = await readFile(project.instrumentationPath, 'utf8')
    if (isStackNextIntegrated(source)) {
      printCheck('pass', 'Instrumentation already imports @stacknext/next')
    } else {
      printCheck(
        'warn',
        'Existing instrumentation.ts was left untouched',
        'Add the hook below so your current monitoring keeps working:',
      )
      console.log(`\n${manualPatchSnippet()}\n`)
    }
  } else {
    const target = instrumentationTarget(project)
    await writeFile(target, generatedInstrumentation(project.typescript), { mode: 0o600 })
    printCheck('pass', `Created ${path.relative(project.dir, target)}`)
  }

  const declared =
    project.dependencies['@stacknext/next'] ??
    project.devDependencies['@stacknext/next']
  if (!declared) {
    if (options.install) {
      const installed = await runInstall(project)
      if (installed) printCheck('pass', 'Installed @stacknext/next')
      else
        printCheck(
          'warn',
          'Install @stacknext/next before starting Next.js',
          installCommand(project.packageManager, ['@stacknext/next'], true),
        )
    } else {
      printCheck(
        'warn',
        '@stacknext/next is not installed',
        installCommand(project.packageManager, ['@stacknext/next'], true),
      )
    }
  } else {
    printCheck('pass', `@stacknext/next ${declared}`)
  }

  if (project.hasDrizzle) {
    printCheck(
      'warn',
      'Drizzle detected',
      'Add createStackNextDrizzleLogger() from @stacknext/drizzle to your db client.',
    )
  }
  if (project.hasPrisma) {
    printCheck(
      'warn',
      'Prisma detected',
      'Add instrumentPrismaClient() from @stacknext/prisma after creating PrismaClient.',
    )
  }

  printSection('Next steps')
  console.log(
    `1. Run ${style.cyan('stacknext dev')} (or ${style.cyan('stacknext dev --install')} if packages are missing).`,
  )
  console.log(`2. Open the dashboard and make a request to your app.`)
  console.log(`3. Run ${style.cyan('stacknext doctor')} if data does not appear.`)
  return 0
}

export function registerInitCommand(program: Command, cwd: string): void {
  program
    .command('init')
    .description('Configure a Next.js project for StackNext')
    .option('--install', 'install @stacknext/next with the detected package manager')
    .action(async (options: InitOptions) => {
      const code = await runInit(options, cwd)
      if (code !== 0) process.exitCode = code
    })
}
